#include <iostream>

using namespace std;

int main(void){
    int T;
    cin>>T;
    for(int i=0;i<T;i++){
        int N,M;
        cin>>N>>M;
        for(int i=0;i<M;i++){
            int a,b;
            cin>>a>>b;
        }
        cout<<N-1<<'\n';//MST(Minimum Spanning Tree)만들기: Node개수 -1;
    }
}